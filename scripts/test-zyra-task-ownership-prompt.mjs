import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const prompt = read('../prompts/zyra_system_prompt.md');
const ownership = prompt.split('## Task ownership')[1]?.split('\n## ')[0] || '';
assert.ok(ownership, 'the shared system prompt explicitly owns task completion');
for (const pattern of [/deliver the requested outcome/i, /instructions for the user/i, /another authorized route/i, /same failing approach/i, /smallest missing piece/i, /permission|authorization/i, /budget|time/i]) assert.match(ownership, pattern);
assert.match(prompt, /Do not ask for discoverable facts or secrets/);
assert.match(prompt, /explicit approval for that exact action/);
assert.match(prompt, /No mode bypasses target selection/);
assert.match(prompt, /Honor the surface named by the user/);
assert.match(prompt, /Submitted answers return as a real user message and begin a new turn/);
assert.match(prompt, /honor the user's limits on testing and tool use/i);
assert.doesNotMatch(prompt, /Run or name the useful check/);
assert.doesNotMatch(prompt, /Report the failure or reacquire the same exact target instead/);
assert.match(prompt, /commit message only when asked/i);
const sdk = read('../src/zyra-sdk.mjs');
assert.match(sdk, /prompt: path\.join\(ROOT, "prompts\/zyra_system_prompt\.md"\)/);
assert.match(sdk, /injectZyraGuide\(result\.session, readPrompt\(defaults\.prompt\)\)/, 'new runtimes load the shared guide');
assert.match(sdk, /function refreshZyraPromptContext[\s\S]*?injectZyraGuide\(runtime\.session, readPrompt\(defaults\.prompt\)\)/, 'refresh rereads the shared guide');
assert.match(sdk, /export async function reloadZyraRuntime[\s\S]*?refreshZyraPromptContext\(runtime, \{ runMemoryStartup: true \}\)/, 'existing reload refreshes the guide without a new conversation');
console.log('Task ownership prompt: execution, route switching, minimal handoffs, bounded scope and preserved safety/wiring: ok');
