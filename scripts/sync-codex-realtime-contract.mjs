import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const contractPath = resolve(root, "src", "chatgpt-realtime-contract.mjs");
const CODEX_RAW_BASE = "https://raw.githubusercontent.com/openai/codex/main/codex-rs";
const MODEL_SOURCE_URL = `${CODEX_RAW_BASE}/core/src/realtime_conversation.rs`;
const CALL_SOURCE_URL = `${CODEX_RAW_BASE}/codex-api/src/endpoint/realtime_call.rs`;
const ALLOWED_CONTRACT_HOST = "chatgpt.com";
const ALLOWED_CONTRACT_PATH_PREFIX = "/backend-api/codex/";

export function extractCodexRealtimeContract({ modelSource, callSource, headerSource }) {
  const model = modelSource.match(/DEFAULT_FRAMELESS_REALTIME_MODEL:\s*&str\s*=\s*"([^"]+)"/)?.[1];
  const alphaHeader = [...headerSource.matchAll(/HeaderValue::from_static\("(quicksilver=v\d+)"\)/g)]
    .map((match) => match[1])
    .at(-1);
  const endpointCandidates = [...new Set(
    [...callSource.matchAll(/"(https:\/\/chatgpt\.com\/backend-api\/codex\/realtime\/calls\?[^"\s]+)"/g)]
      .map((match) => match[1])
      .filter((value) => {
        const url = new URL(value);
        return url.searchParams.get("intent") === "quicksilver"
          && url.searchParams.get("architecture") === "avas";
      }),
  )];
  const callUrl = endpointCandidates.at(-1);

  const contract = {
    source: "openai/codex@main",
    callUrl,
    model,
    alphaHeader,
  };
  validateCodexRealtimeContract(contract);
  return contract;
}

export function validateCodexRealtimeContract(contract) {
  if (!/^gpt-(?:live|realtime)-[A-Za-z0-9._-]{1,64}$/.test(String(contract.model || ""))) {
    throw new Error(`Refusing unrecognized Codex realtime model: ${String(contract.model || "missing")}`);
  }
  if (!/^quicksilver=v\d+$/.test(String(contract.alphaHeader || ""))) {
    throw new Error(`Refusing unrecognized Codex realtime alpha header: ${String(contract.alphaHeader || "missing")}`);
  }

  let callUrl;
  try {
    callUrl = new URL(contract.callUrl);
  } catch {
    throw new Error("Refusing an invalid Codex realtime call URL.");
  }
  if (callUrl.protocol !== "https:"
    || callUrl.hostname !== ALLOWED_CONTRACT_HOST
    || !callUrl.pathname.startsWith(ALLOWED_CONTRACT_PATH_PREFIX)
    || callUrl.searchParams.get("intent") !== "quicksilver"
    || callUrl.searchParams.get("architecture") !== "avas"
    || [...callUrl.searchParams].length !== 2) {
    throw new Error(`Refusing non-allowlisted Codex realtime call URL: ${callUrl.href}`);
  }
}

export function renderCodexRealtimeContract(contract) {
  validateCodexRealtimeContract(contract);
  return `// Generated by scripts/sync-codex-realtime-contract.mjs from the public\n`
    + `// openai/codex realtime contract. Review changes before committing this file.\n`
    + `export const CHATGPT_REALTIME_CONTRACT_SOURCE = ${JSON.stringify(contract.source)};\n`
    + `export const CHATGPT_REALTIME_CALL_URL = ${JSON.stringify(contract.callUrl)};\n`
    + `export const CHATGPT_REALTIME_MODEL = ${JSON.stringify(contract.model)};\n`
    + `export const CHATGPT_REALTIME_ALPHA_HEADER = ${JSON.stringify(contract.alphaHeader)};\n`;
}

export async function readUpstreamCodexRealtimeContract(fetchImpl = globalThis.fetch) {
  if (typeof fetchImpl !== "function") throw new Error("fetch is unavailable");
  const readSource = async (url) => {
    const response = await fetchImpl(url, {
      headers: { Accept: "text/plain", "User-Agent": "zyra-codex-contract-sync/1.0" },
      redirect: "error",
    });
    if (!response.ok) throw new Error(`Could not read ${url} (${response.status}).`);
    const source = await response.text();
    if (!source || source.length > 4 * 1024 * 1024) throw new Error(`Refusing invalid upstream source from ${url}.`);
    return source;
  };
  const [modelSource, callSource] = await Promise.all([
    readSource(MODEL_SOURCE_URL),
    readSource(CALL_SOURCE_URL),
  ]);
  return extractCodexRealtimeContract({ modelSource, callSource, headerSource: modelSource });
}

async function main() {
  const mode = process.argv.includes("--write") ? "write" : "check";
  const upstream = await readUpstreamCodexRealtimeContract();
  const expected = renderCodexRealtimeContract(upstream);
  const current = await readFile(contractPath, "utf8").catch(() => "");
  if (current === expected) {
    console.log(`[codex-realtime-contract] current: ${upstream.model}`);
    return;
  }
  if (mode === "write") {
    await writeFile(contractPath, expected, "utf8");
    console.log(`[codex-realtime-contract] updated: ${upstream.model}`);
    return;
  }
  console.error("[codex-realtime-contract] Zyra differs from the reviewed public Codex realtime contract.");
  console.error(`Run \`npm run voice:sync-codex-contract\` and review ${contractPath}.`);
  process.exitCode = 1;
}

const directRunPath = process.argv[1] ? resolve(process.argv[1]) : "";
if (directRunPath === fileURLToPath(import.meta.url)) {
  await main();
}
