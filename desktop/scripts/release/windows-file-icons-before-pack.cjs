const { existsSync } = require('node:fs')
const path = require('node:path')
const manifest = require('material-icon-theme/dist/material-icons.json')

function windowsFileAssociations(associations) {
    return associations.flatMap(association => [].concat(association.ext).map(ext => {
        const definition = manifest.fileExtensions[ext] || manifest.file
        return {
            ...association,
            ext: [ext],
            // NSIS uses `name` as the ProgID. Sharing it means the last icon wins.
            name: `Zyra.File.${ext}`,
            icon: `resources/file-icons/zyra-file-${definition}.ico`
        }
    }))
}

module.exports = function beforePack(context) {
    if (context.electronPlatformName !== 'win32') return
    const { config, projectDir, platformSpecificBuildOptions = {} } = context.packager
    const associations = windowsFileAssociations([
        ...[].concat(config.fileAssociations || []),
        ...[].concat(platformSpecificBuildOptions.fileAssociations || [])
    ])
    for (const association of associations) {
        if (!existsSync(path.resolve(projectDir, association.icon))) {
            throw new Error(`Missing Windows file icon: ${association.icon}. Run npm run icons:windows.`)
        }
    }
    // NSIS reads this packager getter. Override only the Windows instance:
    // mutating config would also alter macOS/Linux during a multi-platform build.
    Object.defineProperty(context.packager, 'fileAssociations', {
        configurable: true,
        value: associations
    })
}
module.exports.windowsFileAssociations = windowsFileAssociations

function windowsFileIconNsis(associations) {
    const rows = windowsFileAssociations(associations)
    const install = rows.flatMap(item => [
        `  WriteRegStr SHELL_CONTEXT "Software\\Classes\\.${item.ext[0]}\\DefaultIcon" "" "$INSTDIR\\resources\\${path.basename(item.icon)}"`,
        `  WriteRegStr SHELL_CONTEXT "Software\\Classes\\${item.name}\\shell\\open\\command" "" '\"$appExe\" \"%1\"'`
    ])
    const uninstall = rows.flatMap(item => {
        const key = `Software\\Classes\\.${item.ext[0]}\\DefaultIcon`
        return [
            `  ReadRegStr $0 SHELL_CONTEXT "${key}" ""`,
            `  \${If} $0 == "$INSTDIR\\resources\\${path.basename(item.icon)}"`,
            `    DeleteRegValue SHELL_CONTEXT "${key}" ""`,
            `    DeleteRegKey /ifempty SHELL_CONTEXT "${key}"`,
            '  ${EndIf}',
            `  ReadRegStr $0 SHELL_CONTEXT "Software\\Classes\\.${item.ext[0]}" ""`,
            `  \${If} $0 == "${item.name}"`,
            `    DeleteRegValue SHELL_CONTEXT "Software\\Classes\\.${item.ext[0]}" ""`,
            '  ${EndIf}'
        ]
    })
    return [
        '; Generated by npm run icons:windows. Do not edit by hand.',
        '; Windows uses extension icons when no explicit default-app choice exists.',
        '!macro ZyraInstallFileIcons', ...install, '!macroend', '',
        '!macro ZyraUninstallFileIcons', ...uninstall, '!macroend', ''
    ].join('\n')
}
module.exports.windowsFileIconNsis = windowsFileIconNsis
